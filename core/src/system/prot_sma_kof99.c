/* `cmc_prot_device::decrypt()`: um "passo" de XOR sobre um par de bytes. */
/* Tabelas do CMC50 (KOF2000 e família) e da M1 cifrada — GERADAS
 * automaticamente a partir de `prot_cmc.cpp` do MAME (script Python lendo o
 * fonte, sem redigitar), no Achado #81. As 9 tabelas do CMC42 acima foram
 * conferidas contra o mesmo fonte pelo mesmo método: idênticas. */
#include "cmc50_tables.inc"

typedef struct {
    const u8 *type0_t03, *type0_t12, *type1_t03, *type1_t12;
    const u8 *address_8_15_xor1, *address_8_15_xor2;
    const u8 *address_16_23_xor1, *address_16_23_xor2;
    const u8 *address_0_7_xor;
} cmc_tables_t;

static const cmc_tables_t cmc42_tables = {
    kof99_type0_t03, kof99_type0_t12, kof99_type1_t03, kof99_type1_t12,
    kof99_address_8_15_xor1, kof99_address_8_15_xor2,
    kof99_address_16_23_xor1, kof99_address_16_23_xor2, kof99_address_0_7_xor,
};
static const cmc_tables_t cmc50_tables = {
    kof2000_type0_t03, kof2000_type0_t12, kof2000_type1_t03, kof2000_type1_t12,
    kof2000_address_8_15_xor1, kof2000_address_8_15_xor2,
    kof2000_address_16_23_xor1, kof2000_address_16_23_xor2, kof2000_address_0_7_xor,
};

/* `cmc_prot_device::decrypt` — note que ele usa o `address_0_7_xor` do
 * conjunto ATIVO, então precisa receber as tabelas. */
static void cmc_decrypt_pair(const cmc_tables_t *t, u8 *r0, u8 *r1, u8 c0, u8 c1,
                              const u8 *table0hi, const u8 *table0lo, const u8 *table1,
                              u32 base, int invert) {
    u8 tmp = table1[(base & 0xffu) ^ t->address_0_7_xor[(base >> 8) & 0xffu]];
    u8 xor0 = (u8)((table0hi[(base >> 8) & 0xffu] & 0xfeu) | (tmp & 0x01u));
    u8 xor1 = (u8)((tmp & 0xfeu) | (table0lo[(base >> 8) & 0xffu] & 0x01u));
    if (invert) { *r0 = (u8)(c1 ^ xor0); *r1 = (u8)(c0 ^ xor1); }
    else        { *r0 = (u8)(c0 ^ xor0); *r1 = (u8)(c1 ^ xor1); }
}

/* `cmc_prot_device::gfx_decrypt()`. Roda sobre o buffer COMBINADO (odd+even
 * intercalados, layout MAME). CMC42 e CMC50 são o MESMO algoritmo; só muda o
 * conjunto de tabelas (e a chave `extra_xor`, por jogo). */
static void cmc_gfx_decrypt(const cmc_tables_t *t, u8 *rom, u32 rom_size, int extra_xor) {
    u8 *buf = (u8 *)malloc(rom_size);
    if (!buf) return;

    for (u32 rpos = 0; rpos < rom_size / 4u; rpos++) {
        cmc_decrypt_pair(t, &buf[4u*rpos+0u], &buf[4u*rpos+3u], rom[4u*rpos+0u], rom[4u*rpos+3u],
                          t->type0_t03, t->type0_t12, t->type1_t03, rpos, (int)((rpos>>8)&1u));
        cmc_decrypt_pair(t, &buf[4u*rpos+1u], &buf[4u*rpos+2u], rom[4u*rpos+1u], rom[4u*rpos+2u],
                          t->type0_t12, t->type0_t03, t->type1_t12, rpos,
                          (int)(((rpos>>16) ^ t->address_16_23_xor2[(rpos>>8)&0xffu]) & 1u));
    }

    for (u32 rpos = 0; rpos < rom_size / 4u; rpos++) {
        u32 baser = rpos;
        baser ^= (u32)extra_xor;
        baser ^= (u32)t->address_8_15_xor1[(baser >> 16) & 0xffu] << 8;
        baser ^= (u32)t->address_8_15_xor2[baser & 0xffu] << 8;
        baser ^= (u32)t->address_16_23_xor1[baser & 0xffu] << 16;
        baser ^= (u32)t->address_16_23_xor2[(baser >> 8) & 0xffu] << 16;
        baser ^= t->address_0_7_xor[(baser >> 8) & 0xffu];
        /* Achado #75: o recorte normal (`baser &= rom_size/4 - 1`) só funciona
         * quando rom_size é potência de 2. Dois cartuchos não são, e o MAME
         * trata cada um à mão em `cmc_prot_device::gfx_decrypt` — copiado
         * literal daqui:
         *   if (rom_size == 0x3000000)   // preisle2, 48MB
         *   else if (rom_size == 0x6000000) // kf2k3pcb, 96MB
         * A ideia é a mesma nos dois: a parte que cabe numa potência de 2
         * recorta normal, e o "resto" recorta dentro do próprio pedaço. */
        if (rom_size == 0x3000000u) {            /* preisle2 */
            if (rpos < 0x2000000u / 4u) baser &= (0x2000000u / 4u) - 1u;
            else baser = 0x2000000u / 4u + (baser & ((0x1000000u / 4u) - 1u));
        } else if (rom_size == 0x6000000u) {     /* kf2k3pcb */
            if (rpos < 0x4000000u / 4u) baser &= (0x4000000u / 4u) - 1u;
            else baser = 0x4000000u / 4u + (baser & ((0x1000000u / 4u) - 1u));
        } else {
            baser &= (rom_size / 4u) - 1u;
        }

        memcpy(rom + 4u*rpos, buf + 4u*baser, 4u);
    }
    free(buf);
}

void neogeo_cmc42_gfx_decrypt(u8 *rom, u32 rom_size, int extra_xor) {
    cmc_gfx_decrypt(&cmc42_tables, rom, rom_size, extra_xor);
}

void neogeo_cmc50_gfx_decrypt(u8 *rom, u32 rom_size, int extra_xor) {
    cmc_gfx_decrypt(&cmc50_tables, rom, rom_size, extra_xor);
}

/* ===================== CMC50: M1 (programa do Z80) cifrada ================
 * `cmc_prot_device::m1_address_scramble` + `cmc50_m1_decrypt`. O chip soma os
 * primeiros 64KB da M1 CIFRADA (soma simples de bytes em 16 bits —
 * `util::sum16_creator::simple`) e usa isso como chave pra embaralhar os
 * endereços. Não há XOR de dado: é só permutação de posição. */
static u32 m1_address_scramble(u32 address, u16 key) {
    static const int p1[8][16] = {
        {15,14,10,7,1,2,3,8,0,12,11,13,6,9,5,4},
        {7,1,8,11,15,9,2,3,5,13,4,14,10,0,6,12},
        {8,6,14,3,10,7,15,1,4,0,2,5,13,11,12,9},
        {2,8,15,9,3,4,11,7,13,6,0,10,1,12,14,5},
        {1,13,6,15,14,3,8,10,9,4,7,12,5,2,0,11},
        {11,15,3,4,7,0,9,2,6,14,12,1,8,5,10,13},
        {10,5,13,8,6,15,1,14,11,9,3,0,12,7,4,2},
        {9,3,7,0,2,12,4,11,14,10,5,8,15,13,1,6},
    };
    static const int key_bits[16] = { 12,0,2,4,8,15,7,13,10,1,3,6,11,9,14,5 };
    static const int out_bits[16] = { 7,15,14,6,5,13,12,4,11,3,10,2,9,1,8,0 };
    u32 block = (address >> 16) & 7u;
    u32 aux = address & 0xffffu;

    aux ^= bitswap_n(key, key_bits, 16);
    /* bitswap<16>(aux, p1[block][15], ..., p1[block][0]) */
    int order[16];
    for (int k = 0; k < 16; k++) order[k] = p1[block][15 - k];
    aux = bitswap_n(aux, order, 16);
    aux ^= m1_address_0_7_xor[(aux >> 8) & 0xffu];
    aux ^= (u32)m1_address_8_15_xor[aux & 0xffu] << 8;
    aux = bitswap_n(aux, out_bits, 16);

    return (block << 16) | aux;
}

/* Recebe a M1 CIFRADA (`in`, `in_size` bytes — 256KB ou 512KB) e devolve em
 * `out` os 0x80000 bytes decifrados. No MAME a região "audiocrypt" tem 0x80000
 * com o arquivo no começo e o resto zerado; a região de áudio final vira
 * [M1 0..0x10000][M1 0..0x80000], que no nosso modelo (M1 crua, sem a cópia —
 * ver Achado #80) é simplesmente os 0x80000 decifrados. */
void neogeo_cmc50_m1_decrypt(const u8 *in, u32 in_size, u8 *out) {
    static u8 rom[0x80000];
    memset(rom, 0, sizeof(rom));
    memcpy(rom, in, in_size < 0x80000u ? in_size : 0x80000u);
    u16 key = 0;
    for (u32 i = 0; i < 0x10000u; i++) key = (u16)(key + rom[i]);
    for (u32 i = 0; i < 0x80000u; i++) out[i] = rom[m1_address_scramble(i, key)];
}

/* `sfix_decrypt()`: os dados da fix layer, pra esses cartuchos, vêm do
 * FINAL da C ROM já descriptografada (não existe s1.s1 separado). */
void neogeo_cmc_sfix_decrypt(const u8 *rom, u32 rom_size, u8 *fixed, u32 fixed_size) {
    const u8 *src = rom + rom_size - fixed_size;
    for (u32 i = 0; i < fixed_size; i++)
        fixed[i] = src[(i & ~0x1Fu) + ((i & 7u) << 2) + ((~i & 8u) >> 2) + ((i & 0x10u) >> 4)];
}

/* ===================== KOF98 (Achado #82) ==================================
 * `kof98_prot_device::decrypt_68k` (`prot_kof98.cpp`), transcrito. Criptografia
 * de 1998, bem anterior à SMA: só reposiciona pares de bytes dentro dos
 * primeiros 2MB, em blocos de 0x200, e depois empurra os 4MB da sp2 de
 * $200000 pra $100000. Como tudo são cópias de 2 bytes inteiros, não há
 * questão de endianness. */
void neogeo_kof98_decrypt_68k(u8 *src) {
    static const u32 sec[] = { 0x000000, 0x100000, 0x000004, 0x100004, 0x10000a, 0x00000a, 0x10000e, 0x00000e };
    static const u32 pos[] = { 0x000, 0x004, 0x00a, 0x00e };
    u8 *dst = (u8 *)malloc(0x200000u);
    if (!dst) return;
    memcpy(dst, src, 0x200000u);
    for (u32 i = 0x800u; i < 0x100000u; i += 0x200u) {
        for (u32 j = 0; j < 0x100u; j += 0x10u) {
            for (u32 k = 0; k < 16u; k += 2u) {
                memcpy(&src[i+j+k],       &dst[i+j+sec[k/2]+0x100], 2);
                memcpy(&src[i+j+k+0x100], &dst[i+j+sec[k/2]],       2);
            }
            if (i >= 0x080000u && i < 0x0c0000u) {
                for (u32 k = 0; k < 4u; k++) {
                    memcpy(&src[i+j+pos[k]],       &dst[i+j+pos[k]],       2);
                    memcpy(&src[i+j+pos[k]+0x100], &dst[i+j+pos[k]+0x100], 2);
                }
            } else if (i >= 0x0c0000u) {
                for (u32 k = 0; k < 4u; k++) {
                    memcpy(&src[i+j+pos[k]],       &dst[i+j+pos[k]+0x100], 2);
                    memcpy(&src[i+j+pos[k]+0x100], &dst[i+j+pos[k]],       2);
                }
            }
        }
        memcpy(&src[i+0x000000], &dst[i+0x000000], 2);
        memcpy(&src[i+0x000002], &dst[i+0x100000], 2);
        memcpy(&src[i+0x000100], &dst[i+0x000100], 2);
        memcpy(&src[i+0x000102], &dst[i+0x100100], 2);
    }
    memmove(&src[0x100000], &src[0x200000], 0x400000);
    free(dst);
}
