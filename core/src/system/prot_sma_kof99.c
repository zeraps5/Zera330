/* Achado #72: chip de proteção SMA + CMC42 do King of Fighters '99.
 *
 * A partir de 1999, a SNK passou a colocar um chip próprio ("neo-sma") no
 * cartucho que criptografa o PROGRAMA (P ROM) e as GRÁFICAS de sprite
 * (C ROMs) — não é mais só um "leitor de bit" como o Metal Slug X
 * (Achado #69): aqui o conteúdo de verdade sai embaralhado da ROM e
 * precisa ser DESCRIPTOGRAFADO por inteiro antes de rodar.
 *
 * Tudo copiado de fonte primária do MAME, sem adivinhação:
 *   - `src/devices/bus/neogeo/prot_sma.cpp` (sma_prot_device) — descriptografia
 *     do 68k, tabela de bankswitch e o gerador de número "aleatório" da
 *     checagem anti-pirataria.
 *   - `src/devices/bus/neogeo/prot_cmc.cpp` (cmc_prot_device) — descriptografia
 *     das C ROMs (CMC42) e reconstrução da fix layer (que nesses cartuchos
 *     não vem mais separada — os dados dela ficam no FINAL da C ROM).
 *
 * Achado importante ao ler o `ROM_START(kof99)` real (não só o device): o
 * arquivo "ka.neo-sma" (256KB, o próprio chip customizado dumpado) já traz
 * pronta a faixa $0C0000-$0FFFFF do programa — só a faixa $000000-$0BFFFF
 * (o resto do banco fixo) precisa ser RECONSTRUÍDA pelo passo 3 do
 * descriptografador (copiando de dentro da área bancada, ela mesma já
 * descriptografada pelo passo 1). Sem o "ka.neo-sma" carregado no lugar
 * certo, essa reconstrução aponta pra lixo.
 */

#include "neocore/neogeo.h"
#include <stdlib.h>
#include <stdio.h>
#include <string.h>

/* Permutação de bits genérica, no MESMO sentido do `bitswap<N>(v, b_N-1, ...,
 * b0)` do MAME: o primeiro índice da lista alimenta o bit MAIS significativo
 * do resultado. Evita reescrever uma função por tamanho (o MAME usa
 * bitswap<6>, <10>, <16>, <19> nos vários pontos deste arquivo). */
static u32 bitswap_n(u32 v, const int *src_bits_msb_first, int n_bits) {
    u32 r = 0;
    for (int k = 0; k < n_bits; k++) {
        int outpos = n_bits - 1 - k;
        if ((v >> src_bits_msb_first[k]) & 1u) r |= (u32)(1u << outpos);
    }
    return r;
}

/* ===================== SMA: descriptografia do 68k (KOF99) ================ */

u32 neogeo_kof99_bank_base(u16 sel) {
    static const u32 bankoffset[33] = {
        0x000000, 0x100000, 0x200000, 0x300000,
        0x3cc000, 0x4cc000, 0x3f2000, 0x4f2000,
        0x407800, 0x507800, 0x40d000, 0x50d000,
        0x417800, 0x517800, 0x420800, 0x520800,
        0x424800, 0x524800, 0x429000, 0x529000,
        0x42e800, 0x52e800, 0x431800, 0x531800,
        0x54d000, 0x551000, 0x567000, 0x592800,
        0x588800, 0x581800, 0x599800, 0x594800,
        0x598000,
    };
    static const int bits[6] = { 5, 12, 10, 8, 6, 14 }; /* bitswap<6>(sel,5,12,10,8,6,14) */
    u32 data = bitswap_n(sel, bits, 6);
    if (data >= 33u) data = 0u;
    return 0x100000u + bankoffset[data];
}

u16 neogeo_sma_random_step(u16 *state) {
    u16 old = *state;
    u16 newbit = (u16)(((*state >> 2) ^ (*state >> 3) ^ (*state >> 5) ^ (*state >> 6) ^
                        (*state >> 7) ^ (*state >> 11) ^ (*state >> 12) ^ (*state >> 15)) & 1u);
    *state = (u16)((*state << 1) | newbit);
    return old;
}

/* `kof99_decrypt_68k` do MAME, transcrito byte a byte. `p` precisa ser um
 * buffer de EXATAMENTE 0x900000 bytes (1MB de banco fixo + 8MB bancados),
 * com "ka.neo-sma" já colocado em $0C0000 e p1/p2 em $100000/$500000 (ver
 * `load_kof99_sma_prom` em rom_loader.c). Só a etapa 1 (troca de bits dos
 * DADOS) trabalha com o VALOR de 16 bits — as etapas 2 e 3 só reposicionam
 * pares de bytes inteiros, então não têm ambiguidade de endianness: usamos
 * memmove de 2 bytes por "palavra", igual o MAME faz com `uint16_t`. */
void neogeo_kof99_decrypt_68k(u8 *p) {
    /* 1) troca de bits dos DADOS na ROM bancada inteira (p1+p2, 8MB) */
    static const int data_bits[16] = { 13,7,3,0,9,4,5,6,1,12,8,14,10,11,2,15 };
    for (u32 i = 0; i < 0x800000u / 2u; i++) {
        u8 *w = p + 0x100000u + 2u * i;
        u16 val = (u16)((w[0] << 8) | w[1]);
        u16 out = (u16)bitswap_n(val, data_bits, 16);
        w[0] = (u8)(out >> 8);
        w[1] = (u8)out;
    }

    /* 2) troca de bits do ENDEREÇO dentro de cada bloco de 0x800 bytes
     * (só nos primeiros 0x600000 bytes da área bancada). */
    static const int addr_bits10[10] = { 6,2,4,9,8,3,1,7,0,5 };
    for (u32 i = 0; i < 0x600000u / 2u; i += 0x800u / 2u) {
        u8 tmp[0x800];
        memcpy(tmp, p + 0x100000u + 2u * i, 0x800u);
        for (u32 j = 0; j < 0x800u / 2u; j++) {
            u32 src = bitswap_n(j, addr_bits10, 10);
            memcpy(p + 0x100000u + 2u * (i + j), tmp + 2u * src, 2u);
        }
    }

    /* 3) reposiciona o banco fixo: $000000-$0BFFFF vem de dentro da área
     * bancada já descriptografada (offset $700000+), permutado por 19 bits
     * de índice. NÃO toca $0C0000-$0FFFFF (onde já está "ka.neo-sma"). */
    static const int addr_bits19[19] = { 18,11,6,14,17,16,5,8,10,12,0,4,3,2,7,9,15,13,1 };
    /* Igual ao MAME: lê e escreve na MESMA região, sem buffer temporário. Só
     * é seguro porque a faixa de leitura ($700000+, ou seja >= 0x380000 em
     * palavras) nunca se sobrepõe com a faixa de escrita (< 0x60000 em
     * palavras) — cada palavra é lida no máximo uma vez, antes de qualquer
     * escrita chegar perto dali. */
    for (u32 i = 0; i < 0xC0000u / 2u; i++) {
        u32 src = 0x700000u / 2u + bitswap_n(i, addr_bits19, 19);
        memcpy(p + 2u * i, p + 2u * src, 2u);
    }
}

/* ===================== SMA genérico (Achado #79) ==========================
 *
 * O KOF99 foi o primeiro. Garou, Metal Slug 3 e KOF2000 usam o MESMO chip
 * SMA, só que cada um com: (a) sua própria permutação de bits dos dados,
 * (b) seu próprio tamanho de bloco na permutação de endereço da área bancada,
 * (c) sua própria origem pra reconstruir o banco fixo, (d) sua própria tabela
 * de bankswitch e (e) endereços de registrador diferentes. Tudo transcrito de
 * `sma_prot_device::*_decrypt_68k` e `*_bank_base` (`prot_sma.cpp`); os
 * endereços vêm do `switch (type)` em `neogeo_base_state::set_slot_idx`
 * (`neogeo.cpp`). A ORDEM das etapas também muda por jogo e importa — a
 * reconstrução do fixo lê de dentro da área bancada. */

typedef struct {
    int         data_bits[16];
    /* permutação de endereço da área bancada */
    u32         blk_bytes;      /* tamanho do bloco em bytes */
    u32         blk_range;      /* quantos bytes da área bancada ela cobre */
    int         blk_nbits;
    int         blk_bits[15];
    /* reconstrução do banco fixo $000000-$0BFFFF */
    u32         fixed_src;      /* offset absoluto da origem */
    int         fixed_bits[19];
    bool        fixed_first;    /* true: fixo ANTES da permutação bancada */
    /* bankswitch */
    int         bank_bits[6];
    const u32  *bankoffset;
    u32         bank_count;
} sma_desc_t;

