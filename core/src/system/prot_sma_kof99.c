u32 neogeo_sma_bank_base(int type, u16 sel) {
    const sma_desc_t *d = sma_desc(type);
    if (!d) return 0x100000u;
    u32 data = bitswap_n(sel, d->bank_bits, 6);
    /* No MAME a tabela é `bankoffset[64]` com o resto zerado — índice além
     * das entradas definidas dá 0, não lixo. */
    u32 off = (data < d->bank_count) ? d->bankoffset[data] : 0u;
    return 0x100000u + off;
}

static void sma_relocate_fixed(u8 *p, const sma_desc_t *d) {
    for (u32 i = 0; i < 0xC0000u / 2u; i++) {
        u32 src = d->fixed_src / 2u + bitswap_n(i, d->fixed_bits, 19);
        memcpy(p + 2u * i, p + 2u * src, 2u);
    }
}

static void sma_swap_banked(u8 *p, const sma_desc_t *d) {
    static u8 tmp[0x10000]; /* maior bloco: mslug3, 0x10000 bytes */
    const u32 words = d->blk_bytes / 2u;
    for (u32 i = 0; i < d->blk_range / 2u; i += words) {
        memcpy(tmp, p + 0x100000u + 2u * i, d->blk_bytes);
        for (u32 j = 0; j < words; j++) {
            u32 src = bitswap_n(j, d->blk_bits, d->blk_nbits);
            memcpy(p + 0x100000u + 2u * (i + j), tmp + 2u * src, 2u);
        }
    }
}

void neogeo_sma_decrypt_68k(int type, u8 *p) {
    const sma_desc_t *d = sma_desc(type);
    if (!d) return;
    /* 1) troca de bits dos DADOS em toda a área bancada (8MB) */
    for (u32 i = 0; i < 0x800000u / 2u; i++) {
        u8 *w = p + 0x100000u + 2u * i;
        u16 val = (u16)((w[0] << 8) | w[1]);
        u16 out = (u16)bitswap_n(val, d->data_bits, 16);
        w[0] = (u8)(out >> 8);
        w[1] = (u8)out;
    }
    /* 2/3) ordem por jogo: garou e mslug3 reconstroem o fixo ANTES de
     * embaralhar a área bancada; kof99 e kof2000, DEPOIS. */
    if (d->fixed_first) { sma_relocate_fixed(p, d); sma_swap_banked(p, d); }
    else                { sma_swap_banked(p, d);    sma_relocate_fixed(p, d); }
}

/* Registradores do chip, por jogo (`set_slot_idx` em neogeo.cpp). */
void neogeo_sma_addrs(int type, u32 *bank_addr, u32 *rand_addr1, u32 *rand_addr2) {
    u32 b = 0, r1 = 0, r2 = 0;
    switch (type) {
    case NEOGEO_SMA_KOF99:   b = 0x2FFFF0u; r1 = 0x2FFFF8u; r2 = 0x2FFFFAu; break;
    case NEOGEO_SMA_GAROU:   b = 0x2FFFC0u; r1 = 0x2FFFCCu; r2 = 0x2FFFF0u; break;
    case NEOGEO_SMA_MSLUG3:  b = 0x2FFFE4u; r1 = 0u;        r2 = 0u;        break; /* sem random no MAME */
    case NEOGEO_SMA_KOF2000: b = 0x2FFFECu; r1 = 0x2FFFD8u; r2 = 0x2FFFDAu; break;
    default: break;
    }
    *bank_addr = b; *rand_addr1 = r1; *rand_addr2 = r2;
}

